/**
 * CSS custom properties (apps/web, packages/ui-web). Names follow COLOR_LANGUAGE v1.3 §7 app
 * aliases. Light is the default; the app-dark theme applies under `prefers-color-scheme: dark`
 * unless `data-theme='light'` forces light, and under an explicit `data-theme='dark'`.
 */
import { brand, brandRoles, neutral, series, type ColorMode } from '../src/color';
import { ergonomics, layout, radii, space } from '../src/space';
import { status } from '../src/status';
import { fontWeight, fonts, typeScale } from '../src/type';

const kebab = (s: string) => s.replace(/[A-Z0-9]+/g, (m) => `-${m.toLowerCase()}`);

/** Variables that change between modes. */
function modeVariables(mode: ColorMode): Record<string, string> {
  const vars: Record<string, string> = {};
  for (const [k, v] of Object.entries(neutral[mode])) vars[`--${kebab(k)}`] = v;
  for (const [k, v] of Object.entries(brandRoles[mode])) vars[`--${kebab(k)}`] = v;
  for (const [band, c] of Object.entries(status[mode])) {
    vars[`--status-${band}`] = c.solid;
    vars[`--status-${band}-bg`] = c.fill;
    vars[`--status-${band}-fg`] = c.text;
  }
  series[mode].forEach((hex, i) => {
    vars[`--series-${i + 1}`] = hex;
  });
  return vars;
}

/** Mode-independent variables: the raw brand ramp, type, spacing, radii, ergonomics. */
function staticVariables(): Record<string, string> {
  const vars: Record<string, string> = {
    '--teal-tint': brand.tint,
    '--teal-lite': brand.lite,
    '--teal-bright': brand.bright,
    '--teal': brand.primary,
    '--teal-deep': brand.deep,
    '--brand-50': brand.tint,
    '--brand-300': brand.lite,
    '--brand-400': brand.bright,
    '--brand-600': brand.primary,
    '--brand-800': brand.deep,
    '--display': fonts.display,
    '--sans': fonts.sans,
    '--mono': fonts.mono,
  };
  for (const [name, s] of Object.entries(typeScale)) {
    const n = kebab(name);
    vars[`--type-${n}-family`] = `var(--${s.family})`;
    vars[`--type-${n}-size`] = `${s.size}px`;
    vars[`--type-${n}-line`] = `${s.lineHeight}px`;
    vars[`--type-${n}-weight`] = String(fontWeight[s.weight]);
  }
  for (const [step, px] of Object.entries(space)) vars[`--space-${step}`] = `${px}px`;
  for (const [k, px] of Object.entries(radii)) vars[`--r-${k}`] = `${px}px`;
  vars['--tap-min'] = `${ergonomics.minTapTarget}px`;
  vars['--body-min'] = `${ergonomics.minBodyFontSize}px`;
  for (const [k, px] of Object.entries(layout)) vars[`--${kebab(k)}`] = `${px}px`;
  return vars;
}

/** Every variable in effect for a mode (light = static + light; dark = static + dark). */
export function cssVariables(mode: ColorMode): Record<string, string> {
  return { ...staticVariables(), ...modeVariables(mode) };
}

function block(selector: string, vars: Record<string, string>, indent = ''): string {
  const body = Object.entries(vars)
    .map(([k, v]) => `${indent}  ${k}: ${v};`)
    .join('\n');
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

/** The full stylesheet written to packages/tokens/tokens.css. */
export function renderCss(): string {
  const dark = modeVariables('dark');
  return [
    '/* GENERATED by packages/tokens/scripts/generate-css.ts from build/css.ts — do not edit. */',
    '/* Source: docs/design/COLOR_LANGUAGE.md v1.3 (app = light register; dark = app dark theme). */',
    '/* --status-* are reserved for HealthScore / RiskBadge (NFR-4, insmartfix/no-status-color). */',
    block(':root', { ...staticVariables(), ...modeVariables('light') }),
    `@media (prefers-color-scheme: dark) {\n${block(":root:not([data-theme='light'])", dark, '  ')}\n}`,
    block(":root[data-theme='dark']", dark),
    '',
  ].join('\n\n');
}
